export function generateProceduralStars(count = 900) {
  const stars = [];
  for (let i = 0; i < count; i++) {
    stars.push({
      name: '',
      ra: Math.random() * 360,
      dec: -70 + Math.random() * 140,
      mag: 1.5 + Math.random() * 3.5
    });
  }
  return stars;
}
